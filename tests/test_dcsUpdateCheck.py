"""Tests for the DCS update check: utils.dcsVersion and the pure parts of tools/checkDcsUpdate.py."""
import json
import os
import sys

projectRoot = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
toolsDir = os.path.join(projectRoot, 'tools')
for path in (projectRoot, toolsDir):
	if path not in sys.path:
		sys.path.insert(0, path)

from checkDcsUpdate import changedSections, cockpitChanges
from utils.dcsVersion import dcsInstallDir, dcsUpdateNotice, readCheckedDcsVersion, readInstalledDcsVersion, writeCheckedDcsVersion


# Start of a real autoupdate.cfg from DCS 2.9.30.
AUTOUPDATE_CFG = '{\n "WARNING": "DO NOT EDIT this file. You may break your install!",\n "version": "2.9.30.28536",\n "timestamp": "20260930-082115",\n "arch": "x86_64",\n "modules": ["WORLD"]\n}\n'


def test_installDirIsAboveTheBinFolder():
	assert dcsInstallDir('C:/Games/DCS World/bin/DCS.exe') == os.path.normpath('C:/Games/DCS World')
	assert dcsInstallDir('C:/Games/DCS World/bin-mt/DCS.exe') == os.path.normpath('C:/Games/DCS World')
	assert dcsInstallDir('') is None


def test_installedVersionComesFromAutoupdateCfg(tmp_path):
	(tmp_path / 'autoupdate.cfg').write_text(AUTOUPDATE_CFG, encoding='utf-8')
	assert readInstalledDcsVersion(str(tmp_path)) == '2.9.30.28536'


def test_installedVersionIsNoneWithoutAReadableCfg(tmp_path):
	assert readInstalledDcsVersion(str(tmp_path)) is None
	assert readInstalledDcsVersion(None) is None
	(tmp_path / 'autoupdate.cfg').write_text('not json', encoding='utf-8')
	assert readInstalledDcsVersion(str(tmp_path)) is None


def test_checkedVersionRoundTrips(tmp_path):
	path = str(tmp_path / 'dcsVersionChecked.json')
	assert readCheckedDcsVersion(path) is None
	writeCheckedDcsVersion('2.9.30.28536', path)
	assert readCheckedDcsVersion(path) == '2.9.30.28536'


def test_noticeOnlyWhenDcsChangedSinceTheCheck():
	assert dcsUpdateNotice('2.9.30.28536', '2.9.30.28536') is None
	notice = dcsUpdateNotice('2.9.31.1000', '2.9.30.28536')
	assert '2.9.31.1000' in notice and '2.9.30.28536' in notice and 'tools/checkDcsUpdate.py' in notice


def test_noticeWhenNeverChecked():
	assert 'tools/checkDcsUpdate.py' in dcsUpdateNotice('2.9.30.28536', None)


def test_noNoticeWhenTheInstalledVersionIsUnknown():
	assert dcsUpdateNotice(None, '2.9.30.28536') is None


# Extraction diff: which top-level sections changed, like the 2.9.30 Mi-24P keybinding fix.
def test_changedSectionsNamesWhatDiffers():
	old = {'elements': {'a': 1}, 'keybindings': [{'name': 'COLD CRANKING', 'valueDown': -1.0}], 'stats': {'totalKeybindings': 963}}
	new = {'elements': {'a': 1}, 'keybindings': [{'name': 'COLD CRANK', 'valueDown': 1.0}], 'stats': {'totalKeybindings': 962}}
	assert changedSections(old, new) == ['keybindings']


def test_changedSectionsIncludesAddedOrRemovedSections():
	assert changedSections({'elements': {}}, {'elements': {}, 'listenedCommands': []}) == ['listenedCommands']
	assert changedSections({'elements': {}}, {'elements': {}}) == []


# Mapping diff: only clickable controls matter; raw and read-only churn is expected after any update.
DISCRETE = {'arg': 321, 'commandId': 3018, 'deviceId': 3, 'positions': 2, 'type': 'discrete'}

def test_cockpitChangesIgnoreRawAndReadOnly():
	old = {'ENG.start': DISCRETE, 'ENG.raw': {'type': 'raw', 'commandId': 1}, 'ind.1.x': {'indicationId': 1}, 'ENG.gone': DISCRETE}
	new = {'ENG.start': {**DISCRETE, 'positions': 3}, 'ENG.raw': {'type': 'raw', 'commandId': 2}, 'ind.1.x': {'indicationId': 2}, 'ENG.new': DISCRETE}
	assert cockpitChanges(old, new) == (['ENG.gone'], ['ENG.new'], ['ENG.start'])
